// Map of word -> WordHint with progressive levels
export const WORD_HINTS_MAP = new Map<string, WordHint>(
  CURATED_WORDS_WITH_HINTS.map((item) => {
    const word = item.word;
    const firstLetter = word[0];
    const lastLetter = word[word.length - 1];
    return [
      word,
      {
        category: item.category,
        hint: item.hint,
        icon: item.icon,
        firstLetter,
        lastLetter,
        level2Hint: `تبدأ بحرف "${firstLetter}" وتنتمي لمجال ${item.category}`,
        level3Hint: `تبدأ بحرف "${firstLetter}" وتنتهي بحرف "${lastLetter}" (${item.hint})`,
      },
    ];
  })
);

